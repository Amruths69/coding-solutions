import java.util.*;
import java.lang.*;
import java.io.*;

class Codechef
{
	public static void main (String[] args) throws java.lang.Exception
	{
		Scanner a=new Scanner(System.in);
		int t=a.nextInt();
		while(t-->0){
		    int n=a.nextInt();
		    int[] arr=new int[n];
		    for(int i=0;i<n;i++){
		        arr[i]=a.nextInt();
		    }
		    int[] brr=new int[n];
		    for(int i=0;i<n;i++){
		        brr[i]=arr[i]+1;
		    }
		    
		}

	}
}
